import { chromium } from 'playwright'
import assert from 'node:assert/strict'
const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'chrome' })
const base = process.env.CHECK_BASE_URL || 'http://127.0.0.1:5174'
try {
  for (const width of [375, 1440]) {
    const page = await browser.newPage({ viewport: { width, height: 1000 } })
    await page.goto(`${base}/year-one#pictures`)
    const book = page.getByRole('region', { name: 'Hult Prize in pictures' })
    await book.scrollIntoViewIfNeeded()
    await page.locator('#pictures img').evaluateAll(imgs => Promise.all(imgs.map(i => i.decode())))
    const leaves = book.locator('.origin-left')
    await page.waitForFunction(() => document.querySelectorAll('.picture-book-stage .origin-left').length === 9)
    assert.equal(await leaves.count(), 9)
    assert.equal(await book.locator('h4').count(), 0)
    const left = leaves.nth(0).locator('img').nth(1)
    const right = leaves.nth(1).locator('img').first()
    assert.equal(await left.getAttribute('src'), await right.getAttribute('src'))
    assert.equal(await left.getAttribute('data-spread-half'), 'left')
    assert.equal(await right.getAttribute('data-spread-half'), 'right')
    assert(Math.abs(await left.evaluate(el => el.clientWidth) - await leaves.first().evaluate(el => el.clientWidth * 2)) <= 1)
    const copyBox = await page.locator('.picture-book-copy').boundingBox()
    const bookBox = await book.boundingBox()
    assert(width > 1200 ? copyBox.x + copyBox.width <= bookBox.x : copyBox.y + copyBox.height <= bookBox.y)
    assert.equal(await book.getByRole('button').count(), 0)
    await leaves.nth(1).click({ position: { x: 30, y: 30 } })
    const transforms = await leaves.nth(1).evaluate(el => new Promise(resolve => {
      const frames = []
      function sample() { frames.push(getComputedStyle(el).transform); if (frames.length < 50) requestAnimationFrame(sample); else resolve(frames) }
      requestAnimationFrame(sample)
    }))
    assert(new Set(transforms).size > 4, 'page rotates through intermediate frames')
    assert.equal(await leaves.nth(1).evaluate(el => el.style.transform), 'rotateY(-180deg)')
    await page.keyboard.press('ArrowLeft')
    assert.equal(await leaves.nth(1).evaluate(el => el.style.transform), 'rotateY(0deg)')
    await page.mouse.move(0, 0)
    await page.waitForTimeout(750)
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'no horizontal overflow')
    await page.locator('#pictures').screenshot({ path: `/tmp/hult-picture-book-${width}.png` })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.keyboard.press('ArrowRight')
    assert.equal(await leaves.first().evaluate(el => getComputedStyle(el).transitionDuration), '0s')
    for (let i = 0; i < 12; i++) await page.keyboard.press('ArrowLeft')
    await leaves.first().click({ position: { x: 30, y: 30 } })
    assert.equal(await leaves.first().evaluate(el => el.style.transform), 'rotateY(-180deg)', 'first leaf stays pinned open')
    assert.equal(await leaves.nth(1).evaluate(el => el.style.transform), 'rotateY(0deg)')
    for (let i = 0; i < 12; i++) await page.keyboard.press('ArrowRight')
    await leaves.last().click({ position: { x: 30, y: 30 } })
    assert.equal(await leaves.last().evaluate(el => el.style.transform), 'rotateY(0deg)', 'last leaf stays pinned open')
    assert.equal(await leaves.nth(7).evaluate(el => el.style.transform), 'rotateY(-180deg)')
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    await leaves.last().hover()
    assert.equal(await leaves.last().evaluate(el => el.style.transform), 'rotateY(0deg)', 'pinned page cannot peek')
    await page.keyboard.press('ArrowLeft')
    assert.equal(await leaves.nth(7).evaluate(el => el.style.transform), 'rotateY(0deg)', 'can turn back from last spread')
    await page.close()
  }
  console.log('Picture book: animated turns, page clicks, hidden controls, keyboard, responsive layout, reduced motion, pinned first/last spreads passed.')
} finally { await browser.close() }
