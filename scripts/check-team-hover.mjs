import { chromium } from 'playwright'
import assert from 'node:assert/strict'
const watchdog = setTimeout(() => process.exit(1), 60000)
const browser = await chromium.launch({ channel: 'chrome', timeout: 10000 })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'no-preference' })
  page.setDefaultTimeout(10000)
  await page.goto('http://127.0.0.1:5174/about', { waitUntil: 'domcontentloaded' })
  const cards = page.locator('.code-hover-card__surface')
  assert.equal(await cards.count(), 7)
  const card = cards.first()
  await card.scrollIntoViewIfNeeded()
  await card.hover()
  assert.equal(await card.getAttribute('aria-expanded'), 'true')
  const letters = card.locator('.code-hover-card__letter')
  assert(await letters.count() > 200)
  const transforms = await letters.nth(200).evaluate(el => new Promise(resolve => {
    const values = []
    function frame() { values.push(getComputedStyle(el).transform); if (values.length < 55) requestAnimationFrame(frame); else resolve(values) }
    requestAnimationFrame(frame)
  }))
  assert(new Set(transforms).size > 3, 'letters animate upward')
  const field = card.locator('.code-hover-card__characters')
  const before = await field.textContent()
  const box = await card.boundingBox()
  await page.mouse.move(box.x + 30, box.y + 30)
  assert.notEqual(await field.textContent(), before)
  await page.screenshot({ path: '/tmp/hult-team-hover-desktop.png' })
  await page.mouse.move(0, 0)
  await card.focus()
  await page.keyboard.press('Enter')
  assert.equal(await card.getAttribute('aria-expanded'), 'true')
  await page.keyboard.press('Escape')
  assert.equal(await card.getAttribute('aria-expanded'), 'false')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await card.hover()
  assert.equal(await letters.first().evaluate(el => getComputedStyle(el).animationName), 'none')
  await page.close()
  const mobile = await browser.newPage({ viewport: { width: 375, height: 900 }, hasTouch: true, isMobile: true })
  await mobile.goto('http://127.0.0.1:5174/about', { waitUntil: 'domcontentloaded' })
  const touchCard = mobile.locator('.code-hover-card__surface').first()
  await touchCard.scrollIntoViewIfNeeded()
  await touchCard.tap()
  assert.equal(await touchCard.getAttribute('aria-expanded'), 'true')
  await mobile.waitForTimeout(1200)
  const text = await touchCard.locator('.code-hover-card__accessible').textContent()
  assert(text.includes('Grayfel Technologies'))
  assert(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await mobile.screenshot({ path: '/tmp/hult-team-hover-mobile.png' })
  await touchCard.tap()
  assert.equal(await touchCard.getAttribute('aria-expanded'), 'false')
  await mobile.close()
  console.log('Passed: seven photo cards, cursor-following character field, upward letter animation, full biographies, keyboard, touch, reduced motion and mobile layout.')
} finally { await browser.close(); clearTimeout(watchdog) }
