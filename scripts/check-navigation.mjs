import { chromium } from 'playwright'
import assert from 'node:assert/strict'

const browser = await chromium.launch(process.env.PLAYWRIGHT_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH } : {})
const base = process.env.CHECK_BASE_URL || 'http://127.0.0.1:5173'
const errors = []
try {
  for (const reducedMotion of ['no-preference', 'reduce']) {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion })
    page.on('pageerror', e => errors.push(e.message))
    await page.goto(base)
    const bar = page.locator('.site-header__nav')
    const start = await bar.boundingBox()
    assert(start.y > 780 && start.y + start.height < 900, 'desktop navigation is a floating bottom bar')
    const program = page.locator('.program-menu').first()
    const partners = page.locator('.program-menu').last()
    await program.locator('summary').hover()
    assert(await program.evaluate(e => e.open), 'hover opens desktop menu')
    await program.locator('.program-menu__panel').evaluate(async element => {
      await new Promise(requestAnimationFrame)
      await Promise.all(element.getAnimations().map(animation => animation.finished.catch(() => {})))
    })
    const panel = await program.locator('.program-menu__panel').boundingBox()
    assert(panel.y + panel.height < start.y, 'dropdown opens above navigation')
    await program.getByRole('link').first().hover()
    assert(await program.evaluate(e => e.open), 'pointer can enter the panel across the gap')
    await partners.locator('summary').hover()
    assert(await partners.evaluate(e => e.open))
    assert.equal(await program.evaluate(e => e.open), false, 'only one dropdown opens')
    await page.mouse.click(20, 200)
    assert.equal(await partners.evaluate(e => e.open), false, 'outside click closes dropdown')
    await program.locator('summary').focus()
    await page.keyboard.press('ArrowUp')
    assert.equal(await page.evaluate(() => document.activeElement.getAttribute('href')), '/about')
    await page.keyboard.press('Escape')
    assert.equal(await program.evaluate(e => e.open), false)
    assert(await program.locator('summary').evaluate(e => e === document.activeElement), 'Escape returns focus')
    await page.keyboard.press('Enter')
    await program.getByRole('link').filter({ hasText: 'This year' }).click()
    await page.waitForURL('**/this-year')
    assert.equal(await program.evaluate(e => e.open), false, 'navigation closes dropdown')
    await page.goto(base)
    await page.evaluate(() => scrollTo(0, 700))
    const scrolled = await bar.boundingBox()
    assert.equal(scrolled.y, start.y, 'desktop navigation stays at the bottom during scroll')
    await page.evaluate(() => scrollTo(0, document.documentElement.scrollHeight))
    assert(await bar.isVisible(), 'desktop navigation stays available at footer')
    const topButton = await page.locator('.scroll-to-top').boundingBox()
    const bottomBar = await bar.boundingBox()
    assert(topButton.x > bottomBar.x + bottomBar.width, 'scroll-to-top does not overlap navigation')
    if (reducedMotion === 'reduce') assert.equal(await bar.evaluate(e => e.getAnimations().length), 0)

    for (const width of [320, 375, 768, 1180]) {
      await page.setViewportSize({ width, height: 800 })
      await page.goto(base)
      const toggle = page.getByRole('button', { name: 'Menu', exact: true })
      const beforeScroll = await toggle.boundingBox()
      await page.evaluate(() => scrollTo(0, 500))
      assert.deepEqual(await toggle.boundingBox(), beforeScroll, 'mobile Menu remains fixed while scrolling')
      await toggle.click()
      const dialog = page.getByRole('dialog', { name: 'Main menu' })
      assert(await dialog.isVisible())
      assert.equal(await page.evaluate(() => document.body.style.overflow), 'hidden')
      assert.equal(await dialog.evaluate(e => e.matches(':modal')), true)
      await page.keyboard.press('Tab')
      assert(await dialog.evaluate(e => e.contains(document.activeElement)), 'Tab wraps within mobile menu')
      await page.keyboard.press('Shift+Tab')
      assert(await dialog.evaluate(e => e.contains(document.activeElement)), 'Shift+Tab wraps within mobile menu')
      assert(await dialog.getByRole('link', { name: 'Year one', exact: true }).isVisible())
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${width}: no horizontal overflow`)
      await page.keyboard.press('Escape')
      await dialog.waitFor({ state: 'hidden' })
      assert.equal(await dialog.isVisible(), false)
      assert.equal(await page.evaluate(() => document.body.style.overflow), '')
      assert(await toggle.evaluate(e => e === document.activeElement), 'Escape restores trigger focus')
      await toggle.click()
      await dialog.getByRole('link', { name: 'Year one', exact: true }).click()
      await page.waitForURL('**/year-one')
      await dialog.waitFor({ state: 'hidden' })
      assert.equal(await dialog.isVisible(), false, 'mobile navigation closes dialog')
      await toggle.click()
      await dialog.getByRole('link', { name: 'Year one', exact: true }).click()
      await dialog.waitFor({ state: 'hidden' })
      assert.equal(await dialog.isVisible(), false, 'same-route click also closes dialog')
      if (width <= 700) {
        const footerGroup = page.locator('.site-footer__group').first()
        assert.equal(await footerGroup.evaluate(e => e.open), false, 'mobile footer group starts collapsed')
        await footerGroup.locator('summary').click()
        assert(await footerGroup.evaluate(e => e.open), 'mobile footer group expands')
        await footerGroup.getByRole('link', { name: 'About', exact: true }).click()
        await page.waitForURL('**/about')
      }
      await toggle.click()
      await page.setViewportSize({ width: 1440, height: 900 })
      await page.waitForFunction(() => !document.querySelector('#mobile-navigation').open)
      assert.equal(await page.evaluate(() => document.body.style.overflow), '', 'resizing restores page scrolling')
      for (const group of await page.locator('.site-footer__group').all()) assert(await group.evaluate(e => e.open), 'desktop footer groups are expanded')
    }
    await page.close()
  }
  assert.deepEqual(errors, [])
  console.log('Passed: fixed desktop navigation, upward hover menus, keyboard and dismissal; mobile persistence, modal focus, navigation, resize and overflow at four widths; footer accordions; reduced motion; no runtime errors.')
} finally { await browser.close() }
